#!/usr/bin/env python3
"""Builds the TLS compatibility matrix (markdown) from the results collected by run-matrix.sh."""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

results = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).parent / "results")

KEYS = ["rsa2048", "rsa4096", "rsa1024", "ec256", "ec384", "ec521", "ed25519"]
ENCRYPTIONS = {
	"aes": "OpenSSL 3 default (AES-256 / PBKDF2)",
	"legacy": "OpenSSL -legacy (3DES key, RC2-40 certs)",
	"3des": "3DES / SHA-1",
	"nopbe": "Unencrypted key",
}
CELL = {
	"ok:KEYSTORE": "✅ KS",
	"ok:ENCRYPTED_FILE": "✅ SW",
	"error:UnsupportedEncryption": "❌ enc",
	"error:UnsupportedKeyType": "❌ type",
	"error:UnreadableKey": "❌ key",
	"error:WrongPassword": "❌ pwd",
	"error:KeyUnusable": "❌ unusable",
	"error:NoPrivateKey": "❌ nokey",
	"error:UnrecognizedFormat": "❌ format",
	"error:Expired": "❌ expired",
	"error:WrongOrUnsupportedPassword": "❌ non-ASCII password",
}


def api_of(avd_dir):
	try:
		return int((avd_dir / "api-level").read_text().strip())
	except (OSError, ValueError):
		return 0


def parse_support(file):
	imports, handshakes, hello = {}, {}, {}
	if not file.exists():
		return imports, handshakes, hello
	for line in file.read_text().splitlines():
		parts = [p.strip() for p in line.split("|")]
		if len(parts) != 3:
			continue
		if parts[1].startswith("client/"):
			imports[parts[1][len("client/"):].removesuffix(".p12")] = parts[2]
		elif parts[1].startswith("handshake "):
			handshakes[parts[1][len("handshake "):]] = parts[2]
		elif parts[1].startswith("pqc external "):
			# Handshake with the test Caddy, one per client key: "pqc external host:port groups client-ec.p12"
			handshakes["pqc " + parts[1].split(" ")[-1]] = "ok" if parts[2].startswith("ok ") else parts[2]
		elif parts[1].startswith("clienthello "):
			_, client, field = parts[1].split(" ")
			hello[(client, field)] = [v.strip() for v in parts[2].split(",") if v.strip()]
	return imports, handshakes, hello


def parse_tests(app_dir):
	total = failed = 0
	failures = []
	for xml in app_dir.glob("TEST-*.xml"):
		for case in ET.parse(xml).getroot().iter("testcase"):
			total += 1
			if case.find("failure") is not None:
				failed += 1
				failures.append(case.get("name"))
	return total, failed, failures


avds = sorted((d for d in results.iterdir() if d.is_dir()), key=lambda d: (api_of(d), d.name))
columns = [f"{d.name.removeprefix('TLS_')} ({api_of(d)})" for d in avds]

data = {}
for avd in avds:
	for app in ("tv", "mobile"):
		app_dir = avd / app
		imports, handshakes, hello = parse_support(app_dir / "tls-support.txt")
		total, failed, failures = parse_tests(app_dir)
		crash = (app_dir / "crash.txt").exists() and "FATAL EXCEPTION" in (app_dir / "crash.txt").read_text()
		data[(avd.name, app)] = dict(imports=imports, handshakes=handshakes, hello=hello, total=total, failed=failed,
			failures=failures, crash=crash, present=app_dir.exists())


def row(cells):
	return "| " + " | ".join(cells) + " |"


def header(first):
	return [row([first] + columns), row(["---"] * (len(columns) + 1))]


out = ["# TLS compatibility matrix", "",
	"Generated by `tls-test-matrix/run-matrix.sh` from the device tests (`TlsDeviceTests`).", ""]

# Test summary
out += ["## Test runs", ""] + header("App")
for app in ("tv", "mobile"):
	cells = []
	for avd in avds:
		d = data[(avd.name, app)]
		if not d["present"]:
			cells.append("–")
		elif d["crash"] and d["total"] == 0:
			cells.append("💥 crash")
		elif d["total"] == 0:
			cells.append("⚠️ 0 tests")
		else:
			cells.append(f"{'✅' if d['failed'] == 0 else '❌'} {d['total'] - d['failed']}/{d['total']}")
	out.append(row([app] + cells))
failed_lines = [f"- {avd.name} {app}: {', '.join(data[(avd.name, app)]['failures'])}"
	for avd in avds for app in ("tv", "mobile") if data[(avd.name, app)]["failures"]]
if failed_lines:
	out += ["", "Failed tests:", ""] + failed_lines
out.append("")


def merged_import(avd, name):
	tv = data[(avd, "tv")]["imports"].get(name)
	mobile = data[(avd, "mobile")]["imports"].get(name)
	value = tv or mobile
	cell = CELL.get(value, value or "–")
	if tv and mobile and tv != mobile:
		cell += f" ⚠️ mobile: {CELL.get(mobile, mobile)}"
	return value, cell


# PKCS#12 import matrix
out += ["## PKCS#12 import (client certificate)", "",
	"`✅ KS` stored in AndroidKeyStore · `✅ SW` encrypted software key fallback · "
	"`❌ enc` encryption not readable · `❌ type` key type rejected · `❌ key` key not decodable", ""]
for encryption, title in ENCRYPTIONS.items():
	out += [f"### {title}", ""] + header("Key")
	for key in KEYS:
		out.append(row([key] + [merged_import(avd.name, f"{key}-{encryption}")[1] for avd in avds]))
	out.append("")

# Additional fixtures (e.g. jellyfin-desktop test cases), everything outside the key x encryption matrix
standard = {f"{key}-{encryption}" for key in KEYS for encryption in ENCRYPTIONS}
extra_names = sorted({name for d in data.values() for name in d["imports"] if name not in standard})
if extra_names:
	out += ["### Additional fixtures", ""] + header("File")
	for name in extra_names:
		out.append(row([name] + [merged_import(avd.name, name)[1] for avd in avds]))
	out.append("")

# Summary per Android version
out += ["## Summary per Android version", "", row(["Emulator", "Readable .p12 encryption", "Usable key types"]),
	row(["---"] * 3)]
for avd, column in zip(avds, columns):
	readable = [title for encryption, title in ENCRYPTIONS.items()
		if any((merged_import(avd.name, f"{key}-{encryption}")[0] or "").startswith("ok:") for key in KEYS)]
	usable = [key for key in KEYS
		if any((merged_import(avd.name, f"{key}-{encryption}")[0] or "").startswith("ok:") for encryption in ENCRYPTIONS)]
	out.append(row([column, ", ".join(readable) or "–", ", ".join(usable) or "–"]))
out.append("")

# Handshakes
names = sorted({n for d in data.values() for n in d["handshakes"]},
	key=lambda n: (KEYS.index(n.split()[0]) if n.split()[0] in KEYS else 99, n))
if names:
	out += ["## mTLS handshakes (imported client key)", ""] + header("Key (storage) / client")
	for name in names:
		label = re.sub(r"\((KEYSTORE|ENCRYPTED_FILE)\) ", "", name)
		cells = []
		for avd in avds:
			value = data[(avd.name, "tv")]["handshakes"].get(name) or data[(avd.name, "mobile")]["handshakes"].get(name)
			if value is None:
				# Storage can differ per version, match by key and client only
				candidates = [v for n, v in data[(avd.name, "tv")]["handshakes"].items()
					if re.sub(r"\((KEYSTORE|ENCRYPTED_FILE)\) ", "", n) == label]
				value = candidates[0] if candidates else None
			cells.append("–" if value is None else ("✅" if value == "ok" else "❌ " + value[:60]))
		out.append(row([label] + cells))
	out.append("")

# Capabilities offered in the ClientHello
HELLO_FIELDS = {
	"versions": "TLS versions",
	"groups": "Key exchange groups (incl. post-quantum)",
	"keyshares": "Key shares (groups the first ClientHello is ready for)",
	"ciphers": "Cipher suites",
	"sigalgs": "Signature algorithms (server and client certificates)",
}


def hello_values(avd, client, field):
	for app in ("tv", "mobile"):
		values = data[(avd, app)]["hello"].get((client, field))
		if values is not None:
			return values
	return None


if any(d["hello"] for d in data.values()):
	out += ["## TLS capabilities offered by the app", "",
		"Measured from the ClientHello. `✅` offered by OkHttp (API, WebSocket, images, TV ExoPlayer) and "
		"HttpsURLConnection (mobile ExoPlayer, artwork, crash reports) · `OkHttp` / `URLConn` only by that client · "
		"`–` not offered", ""]
	for field, title in HELLO_FIELDS.items():
		items = []
		for avd in avds:
			for client in ("OkHttp", "HttpsURLConnection"):
				for value in hello_values(avd.name, client, field) or []:
					if value not in items:
						items.append(value)
		if not items:
			continue
		out += [f"### {title}", ""] + header(field)
		for item in items:
			cells = []
			for avd in avds:
				okhttp = hello_values(avd.name, "OkHttp", field)
				urlconn = hello_values(avd.name, "HttpsURLConnection", field)
				if okhttp is None and urlconn is None:
					cells.append("–")
					continue
				in_okhttp = item in (okhttp or [])
				in_urlconn = item in (urlconn or [])
				cells.append("✅" if in_okhttp and in_urlconn else "OkHttp" if in_okhttp else "URLConn" if in_urlconn else "–")
			out.append(row([item] + cells))
		out.append("")

# Simple summary: which Android versions support what

ANDROID = {23: "6", 24: "7", 25: "7.1", 26: "8", 27: "8.1", 28: "9", 29: "10", 30: "11", 31: "12", 32: "12L",
	33: "13", 34: "14", 35: "15", 36: "16", 37: "17"}


def imported_ok(avd, keys, encryptions):
	values = [merged_import(avd, f"{k}-{e}")[0] for k in keys for e in encryptions]
	values = [v for v in values if v]
	return None if not values else any(v.startswith("ok:") for v in values)


def offered(avd, field, predicate):
	values = (hello_values(avd, "OkHttp", field) or []) + (hello_values(avd, "HttpsURLConnection", field) or [])
	if hello_values(avd, "OkHttp", field) is None and hello_values(avd, "HttpsURLConnection", field) is None:
		return None
	return any(predicate(v) for v in values)


def all_tests_pass(avd):
	runs = [data[(avd, app)] for app in ("tv", "mobile") if data[(avd, app)]["present"]]
	if not runs or any(r["total"] == 0 for r in runs):
		return None
	return all(r["failed"] == 0 for r in runs)


def handshake_ok(avd, client):
	results = []
	for app in ("tv", "mobile"):
		for name, value in data[(avd, app)]["handshakes"].items():
			if name.endswith(" " + client):
				results.append(value == "ok")
	return None if not results else all(results)


FEATURES = [
	("All device tests pass", all_tests_pass),
	("Client certificate (mTLS) handshake over TLS 1.2", lambda a: handshake_ok(a, "TLS_1_2")),
	# Not tested where the device has no TLS 1.3 at all, which means it does not work there
	("Client certificate (mTLS) handshake over TLS 1.3", lambda a: handshake_ok(a, "TLS_1_3")
		if handshake_ok(a, "TLS_1_3") is not None or offered(a, "versions", lambda v: v == "TLS 1.3") is not False else False),
	("TLS 1.3 offered", lambda a: offered(a, "versions", lambda v: v == "TLS 1.3")),
	("ChaCha20-Poly1305 cipher suites", lambda a: offered(a, "ciphers", lambda v: "CHACHA20" in v)),
	("X25519 key exchange (ECDHE)", lambda a: offered(a, "groups", lambda v: v == "x25519")),
	("P-384 (secp384r1) key exchange", lambda a: offered(a, "groups", lambda v: v == "secp384r1")),
	("Post-quantum hybrid key exchange (X25519MLKEM768 / ML-KEM)",
		lambda a: offered(a, "groups", lambda v: "MLKEM" in v or "Kyber" in v)),
	("Post-quantum key share in the first ClientHello (no extra round trip)",
		lambda a: offered(a, "keyshares", lambda v: "MLKEM" in v or "Kyber" in v)),
	("Post-quantum mTLS handshake with the test Caddy, EC client key", lambda a: handshake_ok(a, "client-ec.p12")),
	("Post-quantum mTLS handshake with the test Caddy, RSA client key", lambda a: handshake_ok(a, "client-rsa.p12")),
	("Ed25519 or ML-DSA signed server certificates",
		lambda a: offered(a, "sigalgs", lambda v: v in ("ed25519", "mldsa44", "mldsa65", "mldsa87"))),
	(".p12 encrypted with 3DES / SHA-1 (key and certificates)", lambda a: imported_ok(a, KEYS, ["3des"])),
	(".p12 OpenSSL -legacy (3DES key, RC2-40 certificates)", lambda a: imported_ok(a, KEYS, ["legacy"])),
	(".p12 OpenSSL 3 default (AES-256-CBC / PBKDF2 / HMAC-SHA256)", lambda a: imported_ok(a, KEYS, ["aes"])),
	(".p12 with unencrypted private key", lambda a: imported_ok(a, KEYS, ["nopbe"])),
	("RSA 2048 / 4096 client keys", lambda a: imported_ok(a, ["rsa2048", "rsa4096"], ENCRYPTIONS)),
	("RSA 1024 client keys (accepted with warning)", lambda a: imported_ok(a, ["rsa1024"], ENCRYPTIONS)),
	("EC P-256 (secp256r1) client keys", lambda a: imported_ok(a, ["ec256"], ENCRYPTIONS)),
	("EC P-384 (secp384r1) client keys", lambda a: imported_ok(a, ["ec384"], ENCRYPTIONS)),
	("EC P-521 (secp521r1) client keys", lambda a: imported_ok(a, ["ec521"], ENCRYPTIONS)),
	("Ed25519 client keys", lambda a: imported_ok(a, ["ed25519"], ENCRYPTIONS)),
]


def version_label(group):
	apis = sorted({api_of(d) for d in group})
	names = [ANDROID.get(api, f"API {api}") for api in apis]
	label = f"Android {names[0]}" if len(names) == 1 else f"Android {names[0]} – {names[-1]}"
	label += f" (API {apis[0]})" if len(apis) == 1 else f" (API {apis[0]}–{apis[-1]})"
	if any("TV" in d.name for d in group):
		label += ", incl. TV"
	return label


values = {avd.name: {name: check(avd.name) for name, check in FEATURES} for avd in avds}
known = [name for name, _ in FEATURES if any(values[a.name][name] is not None for a in avds)]
if avds and known:
	# Group consecutive versions (sorted by API level) with the same results into one column
	groups = []
	for avd in avds:
		key = tuple(values[avd.name][n] for n in known)
		if groups and groups[-1][0] == key:
			groups[-1][1].append(avd)
		else:
			groups.append((key, [avd]))

	def short_label(group):
		apis = sorted({api_of(d) for d in group})
		names = [ANDROID.get(api, f"API {api}") for api in apis]
		return f"Android {names[0]}" if len(names) == 1 else f"Android {names[0]}–{names[-1]}"

	out += ["## Simple summary", "", "✅ works · ❌ does not work · ? not measured", ""]
	out.append(row(["What"] + [short_label(group) for _, group in groups]))
	out.append(row(["---"] * (len(groups) + 1)))
	for index, name in enumerate(known):
		out.append(row([name] + [{True: "✅", False: "❌", None: "?"}[key[index]] for key, _ in groups]))
	out.append("")
	columns_text = ", ".join(f"{short_label(group)} = {', '.join(d.name.removeprefix('TLS_') for d in group)}"
		for _, group in groups)
	out += [f"Tested emulators: {columns_text}", ""]

print("\n".join(out))
